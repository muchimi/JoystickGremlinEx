"""Generate PyInstaller's Windows version resource from gremlin/version.py."""

import ast
from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parent


def create_version_file(
    output_file: Path = ROOT / "version.txt",
    version_file: Path = ROOT / "gremlin" / "version.py",
) -> Path:
    """Write a UTF-8 VSVersionInfo expression and return its path.

    Windows needs four 16-bit integers: 1.0ex (m77T92) becomes (1, 0, 77, 92).
    Both string version fields retain APPLICATION_VERSION, including suffixes.
    """
    version_tree = ast.parse(version_file.read_text(encoding="utf-8-sig"), filename=str(version_file))
    # Evaluate only the constants, including APPLICATION_VERSION's f-string,
    # without importing gremlin and applying its application startup hooks.
    assignments = [
        node
        for node in version_tree.body
        if isinstance(node, ast.Assign) and all(isinstance(target, ast.Name) and target.id.startswith("APPLICATION_") for target in node.targets)
    ]
    metadata = {}
    exec(
        compile(ast.Module(body=assignments, type_ignores=[]), str(version_file), "exec"),
        {"__builtins__": {}},
        metadata,
    )
    for name in ("APPLICATION_NAME", "APPLICATION_MAIN", "APPLICATION_BASE", "APPLICATION_EXE", "APPLICATION_VERSION"):
        if not isinstance(metadata.get(name), str) or not metadata[name]:
            raise ValueError(f"Missing or invalid {name} in {version_file}")

    main = re.fullmatch(r"([0-9]+)\.([0-9]+)(?:ex)?", metadata["APPLICATION_MAIN"], re.IGNORECASE)
    build = re.fullmatch(r"m([0-9]+)(?:T([0-9]+))?[A-Za-z]*", metadata["APPLICATION_BASE"], re.IGNORECASE)
    if main is None or build is None:
        raise ValueError("Expected APPLICATION_MAIN like '1.0ex' and APPLICATION_BASE like 'm77T92'")
    numeric_version = tuple(int(part or 0) for part in (*main.groups(), *build.groups()))
    if any(part > 65535 for part in numeric_version):
        raise ValueError(f"Windows version components must be between 0 and 65535: {numeric_version}")

    fields = {
        "CompanyName": "EMCS",
        "FileDescription": metadata["APPLICATION_NAME"],
        "FileVersion": metadata["APPLICATION_VERSION"],
        "InternalName": Path(metadata["APPLICATION_EXE"]).stem,
        "LegalCopyright": "Copyright (C) EMCS 2026",
        "OriginalFilename": metadata["APPLICATION_EXE"],
        "ProductName": metadata["APPLICATION_NAME"],
        "ProductVersion": metadata["APPLICATION_VERSION"],
    }
    strings = ",\n".join(f"                StringStruct({name!r}, {value!r})" for name, value in fields.items())
    resource = f"""# -*- coding: utf-8 -*-
# Generated by create_version.py from gremlin/version.py.
VSVersionInfo(
    ffi=FixedFileInfo(
        filevers={numeric_version!r},
        prodvers={numeric_version!r},
        mask=0x3f,
        flags=0x0,
        OS=0x40004,
        fileType=0x1,
        subtype=0x0,
        date=(0, 0),
    ),
    kids=[
        StringFileInfo([
            StringTable('040904b0', [
{strings}
            ]),
        ]),
        VarFileInfo([VarStruct('Translation', [1033, 1200])]),
    ],
)
"""
    output_file.write_text(resource, encoding="utf-8")
    return output_file


if __name__ == "__main__":
    try:
        generated_file = create_version_file()
    except (OSError, SyntaxError, ValueError, NameError) as err:
        print(f"Unable to create GremlinEx version resource: {err}", file=sys.stderr)
        sys.exit(1)
    print(f"Created {generated_file}")
